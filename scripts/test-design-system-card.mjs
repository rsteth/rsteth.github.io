import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8');
const home = read('index.html');
const cards = [...home.matchAll(/<article class="project-card[^" ]*[^"]*"[\s\S]*?<\/article>/g)].map(match => match[0]);
const card = cards.filter(value => value.includes('data-project="design-system"'));
assert.equal(card.length, 1);
assert.match(card[0], /href="https:\/\/stethem.com\/design-system\/"/);
assert.match(card[0], /alt="An illustration of design tokens:/);
assert.match(card[0], /width="800" height="600" loading="lazy" decoding="async"/);
assert.match(card[0], /independent reference studies/);
const data = JSON.parse(home.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]);
const projects = data['@graph'].find(item => item['@type'] === 'ItemList').itemListElement;
assert.equal(projects.length, 10);
projects.forEach((project, index) => assert.equal(project.position, index + 1));
assert.equal(projects.at(-1).name, 'Design System');
assert.equal(projects.at(-1).url, 'https://stethem.com/design-system/');
for (const file of ['index.md', 'llms.txt']) assert.match(read(file), /https:\/\/stethem.com\/design-system\//);
const svg = read('images/apps/design-system.svg');
assert.match(svg, /viewBox="0 0 800 600"/);
assert.match(svg, /Not a screenshot/);
assert.doesNotMatch(svg, /<script|<image|href=|http[s]?:\/\/(?!www.w3.org)/);
console.log('PASS: one Design System card, accessible original illustration, matching ordered structured data and Markdown metadata');
